// The English catalogue — and, because every other language's type is derived from
// it, the definition of what "a complete translation" means.
//
// ── Rules for adding to this file ───────────────────────────────────────────
//
// 1. Keys are namespaced by AREA, dot-separated: `nav.*`, `header.*`, `note.*`.
//    At two hundred entries a flat unnamespaced list stops being readable, and
//    renaming everything later is worse than choosing a prefix now.
// 2. Keys describe the MEANING, not the words. `common.delete` survives a copy
//    change; `common.deleteForever` becomes a lie the moment the button says
//    something else.
// 3. One key per distinct meaning, even when two English strings happen to match.
//    "Archive" the noun and "Archive" the verb are one word in English and two in
//    French (`Archives` / `Archiver`), so sharing a key here would make a correct
//    French translation impossible.
// 4. Placeholders are `{name}`. The types read them out of these literals, so a
//    placeholder renamed here is a compile error at every call site.
// 5. Counted messages are objects of plural forms, never `n + " notes"`.
//
// `as const` is load-bearing twice over: it keeps each value's literal type so
// placeholder names can be extracted from it, and it is what `Catalog` widens from
// so translations are held to the same KEYS without being held to the same WORDS.
