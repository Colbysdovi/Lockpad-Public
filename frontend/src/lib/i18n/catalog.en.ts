/** Every key in the interface. */
export type MessageKey = keyof typeof en;

/** What a translation must provide: the same keys, of the same KIND (a plain string
 *  stays a plain string, a counted message stays counted), with different words.
 *
 *  This is the type that turns an incomplete translation into a build failure. A
 *  French catalogue missing a key does not compile, and neither does one that
 *  answers a counted message with a bare string. */
export type Catalog = {
  [K in MessageKey]: (typeof en)[K] extends string ? string : Message;
};
